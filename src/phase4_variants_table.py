"""Side-by-side H1 and H2 tables: main thresholds next to the pre-declared variants, equal prominence.

Research prototype, not a diagnostic tool. Reads results/phase4/h1_summary.csv and h2_summary.csv only.
No new result is computed. The formal verdicts stay on the main thresholds (pre-registration R1, R5c).

Output: results/phase4/variants_side_by_side.md
Run:    python src/phase4_variants_table.py
"""
from __future__ import annotations

import pandas as pd

from data import ROOT

P4 = ROOT / "results" / "phase4"
V = ["primary", "mchc32", "hgb12", "hgb12_mchc32"]
VN = {"primary": "HGB 13, MCHC 30 (main)", "mchc32": "HGB 13, MCHC 32", "hgb12": "HGB 12, MCHC 30",
      "hgb12_mchc32": "HGB 12, MCHC 32"}
M = ["logreg", "tree", "forest", "hgb"]
MN = {"logreg": "Logistic regression", "tree": "Decision tree", "forest": "Random forest", "hgb": "Gradient boosting"}


def sgn(x: float) -> str:
    return f"{x:+.3f}".replace("-", "−")


def main() -> None:
    h1 = pd.read_csv(P4 / "h1_summary.csv")
    h1 = h1[h1.fset == "F-core"]
    h2 = pd.read_csv(P4 / "h2_summary.csv")
    L = ["Generated by src/phase4_variants_table.py from h1_summary.csv and h2_summary.csv (development CV, F-core).",
         "Formal verdicts use the main thresholds. The variants get the same test and the same space.", "",
         "## H1: hybrid without abstention minus the model alone, macro-F1 (90% CI, pass if the lower bound > −0.03)", "",
         "| Model | Alone | " + " | ".join(VN[v] for v in V) + " |", "|---|---|" + "---|" * len(V)]
    for m in M:
        cells = []
        for v in V:
            r = h1[(h1.variant == v) & (h1.model == m)].iloc[0]
            cells.append(f"{sgn(r['diff'])} [{sgn(r.ci90_lo)}, {sgn(r.ci90_hi)}] {'pass' if r.supported else 'fail'}")
        alone = h1[(h1.variant == "primary") & (h1.model == m)].iloc[0].ml_macro_f1
        L.append(f"| {MN[m]} | {alone:.3f} | " + " | ".join(cells) + " |")
    L.append("| Hybrid macro-F1, random forest | | " + " | ".join(
        f"{h1[(h1.variant == v) & (h1.model == 'forest')].iloc[0].hy_macro_f1:.3f}" for v in V) + " |")
    for floor in [0.70, 0.60, 0.80]:
        tag = " (pre-registered floor)" if floor == 0.70 else " (sensitivity run)"
        L += ["", f"## H2: selective macro-F1 at matched coverage, random forest, coverage floor {floor:.0%}{tag}", "",
              "| Measure | " + " | ".join(VN[v] for v in V) + " |", "|---|" + "---|" * len(V)]
        sub = {v: h2[(h2.variant == v) & (h2.floor.round(2) == floor)].iloc[0] for v in V}
        rows = [("Coverage", lambda r: f"{100 * r.coverage:.1f}%"),
                ("Abstained, rule disagreement", lambda r: f"{100 * r.abstain_disagree:.1f}%"),
                ("Hybrid", lambda r: f"{r.sel_f1_hybrid:.3f}"),
                ("Confidence-only", lambda r: f"{r.sel_f1_confidence:.3f}"),
                ("Random", lambda r: f"{r.sel_f1_random:.3f}"),
                ("Hybrid − random [95% CI], Holm p",
                 lambda r: f"{sgn(r.diff_random)} [{sgn(r.ci95_lo_random)}, {sgn(r.ci95_hi_random)}], {r.p_holm_random:.4f}"),
                ("Hybrid − confidence [95% CI], Holm p",
                 lambda r: f"{sgn(r.diff_confidence)} [{sgn(r.ci95_lo_confidence)}, {sgn(r.ci95_hi_confidence)}], {r.p_holm_confidence:.4f}"),
                ("H2", lambda r: "pass" if r.passes else "fail")]
        for name, f in rows:
            L.append(f"| {name} | " + " | ".join(f(sub[v]) for v in V) + " |")
    taus = pd.read_csv(P4 / "tau_per_fold.csv")
    L += ["", "Folds where the coverage floor could be reached (of 25): " + ", ".join(
        f"{VN[v]} {int(taus[(taus.variant == v) & (taus.floor.round(2) == 0.70)].floor_met.sum())}" for v in V)
          + " (70% floor). Where it cannot be reached, τ = 0 by rule R3, so coverage falls below the floor."]
    (P4 / "variants_side_by_side.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
