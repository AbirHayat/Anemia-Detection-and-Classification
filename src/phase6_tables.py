"""Paper tables for Part D (Phase 6), generated from results/phase6/*.csv. Nothing is recomputed and the test
rows are not read: this script only formats the files written by the single test run.

Research prototype, not a diagnostic tool.

Output: results/phase6/main_results_table_part_d.md
Run:    python src/phase6_tables.py
"""
from __future__ import annotations

import pandas as pd

from data import ROOT

P6 = ROOT / "results" / "phase6"
VN = {"-": "-", "primary": "HGB 13, MCHC 30 (main)", "mchc32": "HGB 13, MCHC 32", "hgb12": "HGB 12, MCHC 30",
      "hgb12_mchc32": "HGB 12, MCHC 32"}


def pct(x):
    return f"{100 * x:.1f}%"


def main() -> None:
    s = pd.read_csv(P6 / "systems.csv")
    a = pd.read_csv(P6 / "agent.csv")
    r = pd.read_csv(P6 / "rules_only.csv")
    m = pd.read_csv(P6 / "mcnemar.csv")
    t = pd.read_csv(P6 / "acceptance_targets.csv")
    pc = pd.read_csv(P6 / "per_class.csv")
    L = ["Generated by src/phase6_tables.py from results/phase6/*.csv (the single held-out test run, 15 Nov 2026, tag "
         "phase6-freeze). 242 valid test rows (5 rejected by the validator). Research prototype.", "",
         "## Systems, nine classes", "",
         "| System | Thresholds | Macro-F1 | Balanced acc. | MCC | Macro-F1 mean-filled | Macro-F1 other |",
         "|---|---|---|---|---|---|---|"]
    for _, x in s.iterrows():
        L.append(f"| {x.system} | {VN[x.thresholds]} | {x.macro_f1:.3f} | {x.balanced_accuracy:.3f} | {x.mcc:.3f} | "
                 f"{x.macro_f1_filled:.3f} | {x.macro_f1_other:.3f} |")
    L += ["", "## Expert system alone", "", "| Thresholds | Rule-set coverage | Mean set size |", "|---|---|---|"]
    for _, x in r.iterrows():
        L.append(f"| {VN[x.thresholds]} | {pct(x.rule_set_coverage)} | {x.mean_set_size:.2f} |")
    L += ["", "## The agent with abstention (frozen settings)", "",
          "| Thresholds | τ | Coverage | Selective macro-F1 | Errors / accepted | Confidence-only (same coverage, descriptive) | Referral caught | False referrals |",
          "|---|---|---|---|---|---|---|---|"]
    for _, x in a.iterrows():
        L.append(f"| {VN[x.thresholds]} | {x.tau:.2f} | {pct(x.coverage)} | {x.selective_macro_f1:.3f} | "
                 f"{int(x.errors_among_accepted)} / {int(x.accepted)} | {x.confidence_only_selective_macro_f1:.3f} | "
                 f"{int(x.referral_caught)}/{int(x.referral_rows)} | {int(x.false_referrals)} |")
    L += ["", "## McNemar tests (continuity-corrected, Holm within each threshold version)", "",
          "| Thresholds | Pair (A vs B) | A right, B wrong | A wrong, B right | p | exact p | Holm p |",
          "|---|---|---|---|---|---|---|"]
    for _, x in m.iterrows():
        L.append(f"| {VN[x.thresholds]} | {x.pair} | {int(x.a_right_b_wrong)} | {int(x.a_wrong_b_right)} | {x.p:.3g} | "
                 f"{x.p_exact:.3g} | {x.p_holm:.3g} |")
    L += ["", "## Acceptance targets", "", "| # | Target | Measured on | Result | Verdict |", "|---|---|---|---|---|"]
    for _, x in t.iterrows():
        L.append(f"| {x.target} | {x.name} | {x.measured_on} | {x.result} | {'pass' if x['pass'] else 'fail'} |")
    L += ["", "## Per-class recall (valid test rows)", "", "| Class | Test rows | Forest | Cascade | Hybrid (main) |",
          "|---|---|---|---|---|"]
    for cls in pc["class"].unique():
        g = pc[pc["class"] == cls]
        get = lambda sysn, th: g[(g.system == sysn) & (g.thresholds == th)].recall.iloc[0]
        n = int(g.support.iloc[0])
        L.append(f"| {cls}{' (caveat: ≤ 5 rows)' if n <= 5 else ''} | {n} | {get('random forest', '-'):.2f} | "
                 f"{get('cascade baseline', '-'):.2f} | {get('hybrid no abstention', 'primary'):.2f} |")
    (P6 / "main_results_table_part_d.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
